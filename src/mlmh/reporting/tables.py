"""LaTeX tables written straight into paper/empirical/tables/."""
from __future__ import annotations

from pathlib import Path

import pandas as pd


def fmt_ci(est: float, lo: float, hi: float, nd: int = 3) -> str:
    if pd.isna(est):
        return "--"
    if pd.isna(lo) or pd.isna(hi):
        return f"{est:.{nd}f}"
    return f"{est:.{nd}f} [{lo:.{nd}f}, {hi:.{nd}f}]"


def write_latex_table(df: pd.DataFrame, path: Path, caption: str, label: str, note: str | None = None, synthetic: bool = False, column_format: str | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if synthetic:
        caption = "[SYNTHETIC FIXTURE -- NOT A RESULT] " + caption
    body = df.to_latex(index=False, escape=True, column_format=column_format, na_rep="--")
    lines = [
        "% Auto-generated by mlmh.reporting.tables -- do not edit by hand.",
        "\\begin{table}[!htbp]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\footnotesize",
        "\\begin{adjustbox}{max width=\\linewidth}",
        body.strip(),
        "\\end{adjustbox}",
    ]
    if note:
        lines.append(f"\\par\\smallskip\\raggedright\\footnotesize {note}")
    lines.append("\\end{table}")
    path.write_text("\n".join(lines) + "\n")
    return path
