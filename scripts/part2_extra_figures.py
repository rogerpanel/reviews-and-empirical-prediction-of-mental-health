"""ECE comparison and radar (spider) figures from the E1 results; SOTA comparison table."""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "paper/empirical/figures"
TAB = ROOT / "paper/empirical/tables"
e1 = pd.read_csv(ROOT / "results/real/E1/e1_results.csv")
e1 = e1[e1.splitter.isin(["subject_wise", "record_wise"]) & (e1.model != "majority")]
LAB = {"logreg": "LogReg", "rf": "RF", "xgboost": "XGB"}

# --- ECE / calibration comparison (grouped bars)
fig, axes = plt.subplots(1, 2, figsize=(7.4, 2.9))
cohorts = ["depresjon", "psykose", "hyperaktiv"]
w = 0.13
for ax, metric, lab in zip(axes, ("window_ece_est", "window_calibration_slope_est"), ("ECE (lower is better)", "Calibration slope (1 = ideal)")):
    x = np.arange(len(cohorts))
    k = 0
    for m in ("logreg", "rf", "xgboost"):
        for sp, hatch, alpha in (("subject_wise", "", 1.0), ("record_wise", "//", 0.55)):
            vals = [e1[(e1.cohort == c) & (e1.model == m) & (e1.splitter == sp)][metric].iloc[0] for c in cohorts]
            ax.bar(x + (k - 2.5) * w, vals, w, label=f"{LAB[m]} {sp.replace('_', '-')}", color={"logreg": "#1f4e5f", "rf": "#6b8e23", "xgboost": "#8c2f1e"}[m], alpha=alpha, hatch=hatch, edgecolor="white", lw=0.4)
            k += 1
    ax.set_xticks(x); ax.set_xticklabels(cohorts, fontsize=8); ax.set_title(lab, fontsize=9)
    ax.spines[["top", "right"]].set_visible(False)
    if "slope" in metric:
        ax.axhline(1.0, color="grey", lw=0.8, ls="--")
axes[0].legend(fontsize=5.5, frameon=False, ncol=2)
fig.tight_layout(); fig.savefig(FIG / "e3_ece_slope_comparison.pdf"); plt.close(fig)

# --- Radar: per model, subject-wise vs record-wise, DEPRESJON and PSYKOSE
def radar_vals(row):
    slope = row["window_calibration_slope_est"]
    slope_score = max(0.0, 1 - abs(1 - slope)) if pd.notna(slope) else 0
    return [row["window_auroc_est"], row["window_balanced_accuracy_mean"], row["window_macro_f1_mean"], 1 - row["window_brier_est"], 1 - row["window_ece_est"], slope_score]

labels = ["AUROC", "Balanced acc.", "Macro-F1", "1 - Brier", "1 - ECE", "Slope score"]
ang = np.linspace(0, 2 * np.pi, len(labels), endpoint=False).tolist(); ang += ang[:1]
fig, axes = plt.subplots(1, 3, figsize=(9.6, 3.4), subplot_kw=dict(polar=True))
for ax, c in zip(axes, cohorts):
    for m, colr in (("logreg", "#1f4e5f"), ("rf", "#6b8e23"), ("xgboost", "#8c2f1e")):
        for sp, ls in (("subject_wise", "-"), ("record_wise", "--")):
            r = e1[(e1.cohort == c) & (e1.model == m) & (e1.splitter == sp)].iloc[0]
            v = radar_vals(r); v += v[:1]
            ax.plot(ang, v, ls=ls, lw=1.1, color=colr, label=f"{LAB[m]} {'subject' if sp == 'subject_wise' else 'record'}-wise")
    ax.set_xticks(ang[:-1]); ax.set_xticklabels(labels, fontsize=6.5); ax.set_ylim(0, 1); ax.set_yticks([0.25, 0.5, 0.75, 1.0]); ax.set_yticklabels(["", ".5", "", "1"], fontsize=6)
    ax.set_title(c, fontsize=9, pad=12)
axes[2].legend(fontsize=5.5, frameon=False, loc="lower right", bbox_to_anchor=(1.35, -0.15))
fig.tight_layout(); fig.savefig(FIG / "e1_radar_models.pdf"); plt.close(fig)

# --- SOTA comparison table: published best claims vs Part II honest / leaky (accuracy and AUROC where reported)
st = pd.read_csv(ROOT / "paper/integrated/part1_studies.csv")
rows = []
for coh, key in (("DEPRESJON", "depresjon"), ("PSYKOSE", "psykose"), ("HYPERAKTIV", "hyperaktiv")):
    sub = st[st.cohorts.str.contains(coh) & (st.best_metric_name == "accuracy") & pd.to_numeric(st.best_metric, errors="coerce").notna()]
    claims = ", ".join(f"{r.id} {float(r.best_metric):.2f}" for _, r in sub.iterrows())
    g = e1[e1.cohort == key]
    sw, rw = g[g.splitter == "subject_wise"], g[g.splitter == "record_wise"]
    rows.append({"Cohort": coh, "Published best accuracies (ID value)": claims or "--",
                 "Part II accuracy, subject-wise (range over models)": f"{sw.window_accuracy_est.min():.2f}--{sw.window_accuracy_est.max():.2f}",
                 "Part II accuracy, record-wise": f"{rw.window_accuracy_est.min():.2f}--{rw.window_accuracy_est.max():.2f}",
                 "Part II AUROC, subject-wise": f"{sw.window_auroc_est.min():.2f}--{sw.window_auroc_est.max():.2f}",
                 "Part II AUROC, record-wise": f"{rw.window_auroc_est.min():.2f}--{rw.window_auroc_est.max():.2f}",
                 "Part II subject-level AUROC, subject-wise": f"{sw.subject_auroc_est.min():.2f}--{sw.subject_auroc_est.max():.2f}"})
df = pd.DataFrame(rows)
body = df.to_latex(index=False, escape=True, column_format="lp{4.2cm}p{1.9cm}p{1.9cm}p{1.9cm}p{1.9cm}p{2.1cm}")
(TAB / "sota_comparison.tex").write_text("% Auto-generated by scripts/part2_extra_figures.py\n\\begin{table}[!htbp]\\centering\\caption{Published best accuracies on each cohort (Part I seed list; Table~\\ref{tab:part1}) against the accuracy and AUROC bands measured in Part II under subject-wise and record-wise five-fold cross-validation (window level unless stated; seed-averaged estimates, range over logistic regression, random forest and XGBoost).}\\label{tab:sota}\\footnotesize\n\\begin{adjustbox}{max width=\\linewidth}\n" + body.strip() + "\n\\end{adjustbox}\\end{table}\n")
print("wrote figures and sota table")
