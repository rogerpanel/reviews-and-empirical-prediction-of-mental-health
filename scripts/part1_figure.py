"""Part I: published claims on the four cohorts against the honest and leaky bands measured in Part II.

Reads paper/integrated/part1_studies.csv (seed extraction; rows marked 'verify' are red in the
table) and results/real/E1/e1_results.csv; writes paper/integrated/figures/part1_claims_vs_bands.pdf
and paper/integrated/part1_studies.tex.
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
st = pd.read_csv(ROOT / "paper/integrated/part1_studies.csv")
e1 = pd.read_csv(ROOT / "results/real/E1/e1_results.csv")
e1 = e1[e1.splitter.isin(["subject_wise", "record_wise"]) & (e1.model != "majority")]

def band(cohort, splitter, col):
    g = e1[(e1.cohort == cohort) & (e1.splitter == splitter)]
    return g[col].min(), g[col].max()

cohort_map = {"DEPRESJON": "depresjon", "PSYKOSE": "psykose", "HYPERAKTIV": "hyperaktiv"}
colors = {"participant": "#1f4e5f", "day/window": "#8c2f1e", "unstated": "#9a8c78"}

def unit(s):
    s = str(s).lower()
    if s.startswith("participant"): return "participant"
    if s.startswith("day"): return "day/window"
    return "unstated"

fig, axes = plt.subplots(1, 3, figsize=(9.6, 3.2), sharey=True)
for ax, coh in zip(axes, cohort_map):
    key = cohort_map[coh]
    for splitter, colr, lab in (("subject_wise", "#1f4e5f", "Part II subject-wise"), ("record_wise", "#8c2f1e", "Part II record-wise")):
        lo, hi = band(key, splitter, "window_accuracy_mean")
        ax.axhspan(lo, hi, color=colr, alpha=0.15, lw=0)
        ax.text(2017.6, (lo + hi) / 2, lab.replace("Part II ", ""), fontsize=6, color=colr, va="center")
    sub = st[st.cohorts.str.contains(coh) & (st.best_metric_name == "accuracy")]
    sub = sub[pd.to_numeric(sub.best_metric, errors="coerce").notna()]
    for _, r in sub.iterrows():
        u = unit(r.split_unit)
        ax.scatter(r.year, float(r.best_metric), color=colors[u], s=28, zorder=3, edgecolor="white", lw=0.5)
        ax.annotate(r.id, (r.year, float(r.best_metric)), fontsize=5.5, xytext=(3, 2), textcoords="offset points")
    ax.set_title(coh, fontsize=9)
    ax.set_xlim(2017.4, 2026.6)
    ax.set_ylim(0.4, 1.0)
    ax.set_xlabel("Year")
    ax.spines[["top", "right"]].set_visible(False)
axes[0].set_ylabel("Reported accuracy (published) / window accuracy (Part II bands)")
h = [plt.Line2D([], [], marker="o", ls="", color=c, label=f"published, split unit: {k}") for k, c in colors.items()]
axes[2].legend(handles=h, fontsize=6, frameon=False, loc="lower right")
fig.tight_layout()
out = ROOT / "paper/integrated/figures/part1_claims_vs_bands.pdf"
out.parent.mkdir(parents=True, exist_ok=True)
fig.savefig(out)
print("wrote", out)

# LaTeX table (red where the extraction must be verified against the full text)
def cell(v):
    v = str(v)
    return v.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")

rows = []
for _, r in st.iterrows():
    mark = "" if r.extraction_basis == "full text" else "$^{a}$"
    rows.append(" & ".join([r.id + mark, cell(r.first_author), str(r.year), cell(r.cohorts), cell(r.best_model), cell(r.split_unit), cell(f"{r.best_metric_name} {r.best_metric}"), cell(r.calibration), cell(r.external_validation), cell(r.code)]) + "\\\\")
tex = ["% Auto-generated by scripts/part1_figure.py from part1_studies.csv",
       "\\begin{table}[!htbp]\\centering\\caption{Part I: eligible published supervised models on the four cohorts (sources in Supplementary Table S4). $^{a}$Extracted from the abstract and metadata (full text not accessible at extraction); n.r.\\ = not reported there. Split unit: participant = leave-one-participant-out or grouped folds; day/window = folds over days or windows; unstated = not stated in the available text.}\\label{tab:part1}\\scriptsize",
       "\\begin{adjustbox}{max width=\\linewidth}\\begin{tabular}{llllllllll}\\toprule",
       "ID & First author & Year & Cohorts & Best model & Split unit & Best reported & Calib. & Ext. val. & Code\\\\\\midrule"] + rows + ["\\bottomrule\\end{tabular}\\end{adjustbox}\\end{table}"]
(ROOT / "paper/integrated/part1_studies.tex").write_text("\n".join(tex) + "\n")
# summary counts for the text
u = st.split_unit.map(unit).value_counts()
print("split units:", u.to_dict(), "| calibration:", st.calibration.value_counts().to_dict(), "| ext val:", st.external_validation.value_counts().to_dict(), "| code:", st.code.value_counts().to_dict(), "| n=", len(st))
